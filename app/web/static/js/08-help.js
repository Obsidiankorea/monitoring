/* ⓘ — 올리면 설명이 뜨고, 누르면 고정(다시 누르거나 밖을 누르면 닫힌다). 벽면 터치에서도 읽히게.
   ⚠️ #pop 에 zoom(--k)이 걸려 있어 left·top 도 그만큼 곱해진다 — 나눠 둔다(재생 막대와 같다). */
let POP_PIN = null;
function showPop(el, pin) {
  const html = TIPS.get(el.dataset.tip);
  if (!html) return;
  const p = $("pop"), k = V?.k || 1, r = el.getBoundingClientRect();
  p.innerHTML = html;
  p.classList.toggle("pin", !!pin);
  p.hidden = false;
  // 긴 문서형 설명(<div class="doc">)은 화면 가운데에 넓게 — 옆에 붙이면 좁은 기둥에 글자가 늘어서 읽기 힘들다
  if (p.classList.toggle("doc", html.startsWith('<div class="doc"'))) {
    const w = p.getBoundingClientRect();
    p.style.left = Math.max(8, (innerWidth - w.width) / 2) / k + "px"; p.style.top = Math.max(8, (innerHeight - w.height) / 2) / k + "px";
    document.querySelectorAll(".inf.pin").forEach(x => x.classList.remove("pin"));
    if (pin) el.classList.add("pin");
    POP_PIN = pin ? el : null;
    return;
  }
  p.style.left = (r.right + 10) / k + "px"; p.style.top = (r.top - 4) / k + "px";
  const pr = p.getBoundingClientRect();
  if (pr.right > innerWidth - 8) p.style.left = Math.max(8, r.left - 10 - pr.width) / k + "px";
  if (pr.bottom > innerHeight - 8) p.style.top = Math.max(8, innerHeight - 8 - pr.height) / k + "px";
  document.querySelectorAll(".inf.pin").forEach(x => x.classList.remove("pin"));
  if (pin) el.classList.add("pin");
  POP_PIN = pin ? el : null;
}
function hidePop() {
  $("pop").hidden = true; POP_PIN = null;
  document.querySelectorAll(".inf.pin").forEach(x => x.classList.remove("pin"));
}
document.addEventListener("mouseover", ev => { const el = ev.target.closest?.(".inf"); if (el && !POP_PIN) showPop(el, false); });
document.addEventListener("mouseout", ev => {
  const el = ev.target.closest?.(".inf");
  if (el && !POP_PIN && !el.contains(ev.relatedTarget)) hidePop();
});
// 잡는 단계에서 — ⓘ 가 레이어 줄(label) 안에 있어 누르면 체크가 바뀌고, 범례 머리에 있으면 접힌다. 그걸 막는다
